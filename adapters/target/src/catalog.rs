use uob_application::{ConfigurationSchema, TargetCapability};
use uob_contracts::TargetKind;

use crate::TransportPolicy;

/// Safe grouping presented to configuration clients.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct TargetDisplayFamily {
    /// Stable machine-readable family, such as `ems-scada`.
    pub id: String,
    /// Human-readable family label.
    pub display_name: String,
}

/// A safe named configuration preset implemented by an existing target factory.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct TargetPreset {
    /// Stable preset identifier accepted by the factory.
    pub id: String,
    /// Human-readable preset label.
    pub display_name: String,
}

/// Composition-root metadata supplied beside a concrete factory.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct TargetRegistration {
    /// UI/catalog grouping independent of the concrete target kind.
    pub display_family: TargetDisplayFamily,
    /// Safe presets implemented by this same factory.
    pub presets: Vec<TargetPreset>,
    /// Optional capabilities exposed before an instance is constructed.
    pub capabilities: Vec<TargetCapability>,
    /// Shared network policy required before factory validation, when applicable.
    pub transport_policy: Option<TransportPolicy>,
}

/// Credential-free catalog entry shared by CLI and browser-facing adapters.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct TargetCatalogEntry {
    /// Stable factory kind.
    pub kind: TargetKind,
    /// Display grouping for this implementation.
    pub display_family: TargetDisplayFamily,
    /// Safe schema generated by the same factory used for validation.
    pub configuration_schema: ConfigurationSchema,
    /// Presets implemented by this factory; a preset is not a second target.
    pub presets: Vec<TargetPreset>,
    /// Optional target capabilities.
    pub capabilities: Vec<TargetCapability>,
    /// Shared network policy applied with trusted environment context.
    pub transport_policy: Option<TransportPolicy>,
    /// Whether this executable contains a factory for the kind.
    pub available: bool,
}

impl TargetCatalogEntry {
    pub(crate) fn new(
        kind: TargetKind,
        configuration_schema: ConfigurationSchema,
        registration: TargetRegistration,
        available: bool,
    ) -> Self {
        Self {
            kind,
            display_family: registration.display_family,
            configuration_schema,
            presets: registration.presets,
            capabilities: registration.capabilities,
            transport_policy: registration.transport_policy,
            available,
        }
    }
}
